"""Controlled 20k-entity training experiment (TRAIN data only).

This is an experiment runner, not part of the library and not `pipeline.py`.
It calls the existing implementations unchanged:

    src.preprocessing  -> src.blocking  -> src.features  -> src.matching

What it does
------------
1. Select ~N_S1 S1 entities by a salted hash (reproducible, order-independent).
2. Stream the ground truth once to learn those S1 entities' true matches.
3. Stream S2 and S3 once, keeping the matched records (so positives are
   present) plus a bounded hash-sampled background (so negatives are
   generated by the real blocking code, never invented).
4. Run the existing blocking, labelling, features, S1-level split and
   LogisticMatcher.
5. Assert the correctness invariants before printing anything.

Why the pool is built this way
------------------------------
A bounded experiment cannot hold all ~7M S2/S3 records. The pool is therefore
the union of (a) every ground-truth match of the selected S1 entities and
(b) a background sample. Consequence, stated plainly: the positive rate here
is a property of this construction, not of the competition dataset, and the
pair-level F0.5 is NOT an end-to-end estimate. End-to-end recall is also
capped by blocking recall over the full S2/S3.

Run:  python experiments/run_experiment_20k.py
"""
from __future__ import annotations

import hashlib
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from src import matching as M                      # noqa: E402
from src.blocking import BlockingIndex, generate_candidates  # noqa: E402
from src.features import FEATURE_NAMES             # noqa: E402

# ----------------------------------------------------------------- config
DATASET = Path(
    r"C:\Users\BITPATNA\Downloads\6ab10eb3b23ba_student_resource"
    r"\student_resource\dataset")
TRAIN = DATASET / "train"

N_S1 = 20_000            # target S1 entities
N_BACKGROUND_S2 = 100_000
N_BACKGROUND_S3 = 100_000

# Reproducibility: these salts and moduli fully determine the subsets.
S1_SALT, S1_MOD = b"exp20k-s1", 110        # ~20k of 2.21M S1 rows
BG_S2_SALT, S2_MOD = b"exp20k-bg2", 20
BG_S3_SALT, S3_MOD = b"exp20k-bg3", 50
SPLIT_SALT = "exp20k-split-v1"
SPLIT_FRACTION = 0.2

OPENED: list[Path] = []


def train_path(name: str) -> Path:
    """Resolve a TRAIN file, refusing anything that looks like test data."""
    if "test" in name.lower():
        raise AssertionError(f"refusing non-train file: {name}")
    path = (TRAIN / name).resolve()
    if path.parent != TRAIN.resolve():
        raise AssertionError(f"refusing path outside train/: {path}")
    if not path.is_file():
        raise FileNotFoundError(path)
    OPENED.append(path)
    return path


def hashed(eid: str, salt: bytes, mod: int) -> bool:
    digest = hashlib.blake2b(eid.encode("utf-8"), key=salt, digest_size=8).digest()
    return int.from_bytes(digest, "big") % mod == 0


T0 = time.perf_counter()
CHECKS: list[tuple[str, bool, str]] = []


def check(name: str, ok: bool, detail: str = "") -> None:
    CHECKS.append((name, bool(ok), detail))
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f" -- {detail}" if detail else ""),
          flush=True)


def step(msg: str) -> None:
    print(f"[{T0 and time.perf_counter() - T0:6.1f}s] {msg}", flush=True)


# ------------------------------------------------------------- 1. S1 subset
print("=" * 78)
print("EXPERIMENT CONFIGURATION")
print("=" * 78)
print(f"  dataset            {DATASET}")
print(f"  files used         {', '.join(p.name for p in [TRAIN])} (train only)")
print(f"  target S1          {N_S1:,}")
print(f"  background S2/S3   {N_BACKGROUND_S2:,} / {N_BACKGROUND_S3:,}")
print(f"  blocking           2tok + addr_ht0 + addr_ht1, cap 1000 (unchanged)")
print(f"  S1 subset salts    S1_SALT={S1_SALT!r} S1_MOD={S1_MOD}")
print(f"  background salts   {BG_S2_SALT!r}/{S2_MOD}  {BG_S3_SALT!r}/{S3_MOD}")
print(f"  split              split_by_reference, fraction={SPLIT_FRACTION}, "
      f"salt={SPLIT_SALT!r}")
print(f"  model              LogisticMatcher defaults "
      f"(lbfgs, C=1.0, class_weight=None, max_iter=1000, random_state=0)")
print()

step("stream S1 -> hash-select subset")
s1_records: dict[str, object] = {}
s1_scanned = 0
for rec in M.iter_records(train_path("train_source1.tsv")):
    s1_scanned += 1
    if len(s1_records) < N_S1 and hashed(rec.entity_id, S1_SALT, S1_MOD):
        s1_records[rec.entity_id] = rec
    if len(s1_records) >= N_S1:
        break
step(f"S1 scanned {s1_scanned:,} rows, selected {len(s1_records):,}")

# ------------------------------------------------- 2. ground truth (1 pass)
step("stream ground truth -> matches for selected S1")
wanted = set(s1_records)
truth: dict[str, frozenset] = {}
with train_path("train_ground_truth.tsv").open(
        "r", encoding="utf-8", errors="replace", newline="") as fh:
    fh.readline()
    for line in fh:
        parts = line.rstrip("\r\n").split("\t")
        if len(parts) < 2 or parts[0].strip() not in wanted:
            continue
        truth[parts[0].strip()] = frozenset(
            p.strip() for p in parts[1].split(",") if p.strip())
matched_ids = {m for v in truth.values() for m in v}
step(f"ground-truth rows captured {len(truth):,}; distinct matched ids {len(matched_ids):,}")

# --------------------------------- 3. pool: matches + hashed background (1 pass)
pool: dict[str, object] = {}
bg_taken = {"S2": 0, "S3": 0}
targets = {"S2": N_BACKGROUND_S2, "S3": N_BACKGROUND_S3}
salts = {"S2": (BG_S2_SALT, S2_MOD), "S3": (BG_S3_SALT, S3_MOD)}
for fname, src in (("train_source2.tsv", "S2"), ("train_source3.tsv", "S3")):
    step(f"stream {fname} -> matches + background")
    salt, mod = salts[src]
    for rec in M.iter_records(train_path(fname)):
        if rec.entity_id in matched_ids:
            pool[rec.entity_id] = rec
        elif bg_taken[src] < targets[src] and hashed(rec.entity_id, salt, mod):
            pool[rec.entity_id] = rec
            bg_taken[src] += 1
n_matched_in_pool = sum(1 for k in pool if k in matched_ids)
step(f"pool {len(pool):,} records = {n_matched_in_pool:,} matched "
     f"+ {len(pool) - n_matched_in_pool:,} background "
     f"(bg S2={bg_taken['S2']:,} S3={bg_taken['S3']:,})")

# ------------------------------------------------------------ 4. candidates
step("build blocking index over pool")
index = BlockingIndex()
index.extend(pool.values(), "POOL")
stats = index.stats()
step(f"index: {stats}")

step("generate candidate pairs for the selected S1 entities")
candidates = []
for eid in sorted(s1_records):
    candidates.extend(generate_candidates(s1_records[eid], index, "S1"))
step(f"candidate pairs {len(candidates):,}")

# ---------------------------------------------------------------- 5. labels
step("label candidates from ground truth")
labelled = M.label_candidates(candidates, truth)
n_pos = sum(i.label for i in labelled)
n_neg = len(labelled) - n_pos
step(f"positives {n_pos:,} / negatives {n_neg:,}")

# -------------------------------------------------------------- 6. features
step("build feature matrix (existing features.py, unchanged)")
records = dict(s1_records)
records.update(pool)
X, y, refs = M.feature_matrix(labelled, records)
step(f"feature matrix {len(X):,} x {len(X[0])}")

# ----------------------------------------------------------------- 7. split
step("S1-level split")
train, val = M.split_by_reference(labelled, validation_fraction=SPLIT_FRACTION,
                                  salt=SPLIT_SALT)
train_ids = {i.pair.reference.entity_id for i in train}
val_ids = {i.pair.reference.entity_id for i in val}
Xtr, ytr, _ = M.feature_matrix(train, records)
Xva, yva, _ = M.feature_matrix(val, records)
tr_pos, tr_neg = sum(ytr), len(ytr) - sum(ytr)
va_pos, va_neg = sum(yva), len(yva) - sum(yva)

# -------------------------------------------------------- 8. correctness
print()
print("=" * 78)
print("CORRECTNESS CHECKS")
print("=" * 78)
non_train = [p for p in OPENED if p.parent != TRAIN.resolve()]
check("no test data loaded", not non_train and all("test" not in p.name.lower()
                                                  for p in OPENED),
      f"opened {len(OPENED)} files, all under train/: "
      f"{', '.join(sorted(p.name for p in OPENED))}")
check("no S1 entity in both train and validation", not (train_ids & val_ids),
      f"train {len(train_ids):,} S1, validation {len(val_ids):,} S1, "
      f"overlap {len(train_ids & val_ids)}")
check("train X/y lengths match", len(Xtr) == len(ytr), f"{len(Xtr):,} == {len(ytr):,}")
check("validation X/y lengths match", len(Xva) == len(yva),
      f"{len(Xva):,} == {len(yva):,}")
check("full-matrix X/y lengths match", len(X) == len(y),
      f"{len(X):,} == {len(y):,}")
widths = {len(r) for r in X}
check("feature vector length == len(FEATURE_NAMES)",
      widths == {len(FEATURE_NAMES)}, f"widths={widths}, "
      f"len(FEATURE_NAMES)={len(FEATURE_NAMES)}")
check("both classes present in training split", tr_pos > 0 and tr_neg > 0,
      f"{tr_pos:,} positive / {tr_neg:,} negative")
bad_cand = {i.pair.candidate.entity_id[:2] for i in labelled} - {"S2", "S3"}
check("all candidate ids belong to S2/S3", not bad_cand, f"prefixes={sorted(
    {i.pair.candidate.entity_id[:2] for i in labelled})}")
check("labels come only from official ground truth",
      all(i.label == (1 if i.pair.candidate.entity_id in
                      truth.get(i.pair.reference.entity_id, frozenset()) else 0)
          for i in labelled),
      f"recomputed {len(labelled):,} labels independently")
nan_free = all(isinstance(v, float) and v == v and abs(v) != float("inf")
               for r in X for v in r)
check("no NaN/inf in feature matrix", nan_free, f"checked {len(X) * len(X[0]):,} values")

# ------------------------------------------------------------------ 9. fit
print()
step("fit LogisticMatcher (defaults, class_weight=None)")
model = M.LogisticMatcher()
model.fit(Xtr, ytr)
s = model.summary
check("Logistic Regression converged", s.converged, f"n_iter={s.n_iter}")

scores = model.predict_proba(Xva)
reports = M.evaluate_thresholds(yva, scores)
best = M.best_validation_threshold(reports)

# ------------------------------------------- 10. class_weight="balanced"
step("fit LogisticMatcher(class_weight='balanced') for comparison")
bal = M.LogisticMatcher(class_weight="balanced").fit(Xtr, ytr)
bal_reports = M.evaluate_thresholds(yva, bal.predict_proba(Xva))
bal_best = M.best_validation_threshold(bal_reports)

# =========================================================== FINAL REPORT
print()
print("=" * 78)
print("FINAL REPORT")
print("=" * 78)

print("\n1. FILES CHANGED")
print("   No source files were modified by this experiment.")
print("   Added: experiments/run_experiment_20k.py (this runner only).")

print("\n2. EXPERIMENT CONFIGURATION")
print(f"   S1 subset      {N_S1:,} entities, salted blake2b (salt={S1_SALT!r}, mod={S1_MOD})")
print(f"   pool           matched records + background "
      f"({N_BACKGROUND_S2:,} S2 / {N_BACKGROUND_S3:,} S3 hashed sample)")
print(f"   blocking       2tok + addr_ht0 + addr_ht1, cap 1000 (unchanged)")
print(f"   split          split_by_reference({SPLIT_FRACTION}, salt={SPLIT_SALT!r})")

print("\n3. DATASET SUBSET SIZE")
print(f"   S1 rows scanned        {s1_scanned:,}")
print(f"   S1 entities selected   {len(s1_records):,}")
print(f"   S1 with GT matches     {len(truth):,}")
print(f"   candidate pool         {len(pool):,}")
print(f"   S1 rows scanned        {s1_scanned:,}")
print(f"   blocking index         {stats.indexed_records:,} records, "
      f"{stats.distinct_keys:,} keys, largest group {stats.largest_group:,}, "
      f"capped groups {stats.capped_groups:,}")

print("\n4-5. CANDIDATES AND LABELS")
print(f"   candidate pairs        {len(candidates):,}")
print(f"   positive candidates    {n_pos:,}")
print(f"   negative candidates    {n_neg:,}")
print(f"   positive rate          {n_pos / max(1, len(labelled)):.4%}")

print("\n6. TRAIN / VALIDATION SPLIT")
print(f"   training pairs         {len(train):,}   ({tr_pos:,} pos / {tr_neg:,} neg)")
print(f"   validation pairs       {len(val):,}   ({va_pos:,} pos / {va_neg:,} neg)")
print(f"   training S1 entities   {len(train_ids):,}")
print(f"   validation S1 entities {len(val_ids):,}")
print(f"   S1 overlap             {len(train_ids & val_ids)}")

print("\n7. FEATURES")
print(f"   feature count          {len(FEATURE_NAMES)}")
for i, n in enumerate(FEATURE_NAMES):
    print(f"     {i:2d}. {n}")

print("\n8. LOGISTIC REGRESSION CONFIGURATION")
print(f"   estimator              sklearn.linear_model.LogisticRegression")
print(f"   solver                 lbfgs")
print(f"   C                      1.0")
print(f"   class_weight           {s.class_weight}")
print(f"   max_iter               1000")
print(f"   random_state           0")
print(f"   n_samples              {s.n_samples:,}")
print(f"   n_positive / n_negative {s.n_positive:,} / {s.n_negative:,} "
      f"({s.positive_rate:.4%} positive)")
print(f"   converged              {s.converged}")
print(f"   n_iter                 {s.n_iter}")

print("\n9. LEARNED COEFFICIENTS  (positive => pushes score toward 1)")
for name, coef in sorted(model.coefficients().items(), key=lambda kv: -abs(kv[1])):
    print(f"   {name:28s} {coef:+.6f}")

print("\n10. VALIDATION THRESHOLD TABLE  (class_weight=None)")
print("   threshold | precision |   recall |    F0.5 | predicted positives")
print("   " + "-" * 66)
for r in reports:
    print(f"   {r.threshold:9.1f} | {r.precision:9.4f} | {r.recall:8.4f} | "
          f"{r.f_beta:8.4f} | {r.predicted_positives:19,}")
print(f"   validation positives total: {va_pos:,}   validation pairs: {len(yva):,}")

print("\n11-12. VALIDATION-ONLY BEST THRESHOLD  (NOT the competition threshold)")
print(f"   threshold              {best.threshold}")
print(f"   F0.5                   {best.f_beta:.4f}")
print(f"   precision / recall     {best.precision:.4f} / {best.recall:.4f}")
print(f"   TP/FP/FN               {best.true_positives:,} / "
      f"{best.false_positives:,} / {best.false_negatives:,}")

print("\n13. class_weight='balanced' COMPARISON")
print("   threshold | precision |   recall |    F0.5 | predicted positives")
print("   " + "-" * 66)
for r in bal_reports:
    print(f"   {r.threshold:9.1f} | {r.precision:9.4f} | {r.recall:8.4f} | "
          f"{r.f_beta:8.4f} | {r.predicted_positives:19,}")
print(f"   balanced best          threshold {bal_best.threshold}, "
      f"F0.5 {bal_best.f_beta:.4f} (P {bal_best.precision:.4f} / R {bal_best.recall:.4f})")
print(f"   default  (None) best   threshold {best.threshold}, F0.5 {best.f_beta:.4f}")
print(f"   difference in F0.5     {bal_best.f_beta - best.f_beta:+.4f} "
      f"({'balanced' if bal_best.f_beta > best.f_beta else 'None'} wins)")

print("\n14. ERRORS / WARNINGS")
print(f"   {'none' if all(ok for _, ok, _ in CHECKS) else 'SEE FAILED CHECKS ABOVE'}")
print(f"   blocking index reported {stats.keyless_records:,} keyless records "
      f"(records with no usable blocking key)")

print("\n15. CHECKS PERFORMED")
for name, ok, detail in CHECKS:
    print(f"   [{'PASS' if ok else 'FAIL'}] {name}" + (f" -- {detail}" if detail else ""))

print("\n" + "=" * 78)
print("INTERPRETATION: this is a first-pass sanity baseline, NOT competition")
print("performance. The positive rate is an artefact of how the bounded pool was")
print("built (true matches kept + sampled background), and the pair-level F0.5")
print("excludes blocking recall against the full ~7M S2/S3 records. The")
print("validation-best threshold was chosen on the same data it is judged on.")
print("=" * 78)
step("done")
